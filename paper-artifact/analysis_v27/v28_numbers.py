"""v28 additions to the v27 re-analysis. Reads results/ only and writes
  paper-v28/numbers_v28.tex   (\\defnum{v28:...}{...}; never redefines a numbers.tex or v27: key)
  analysis_v27/out_v28/*.csv   (computed rows, for audit)

Sections
  F  Holm correction over the post hoc Fisher tests of the Stripe cells against their
     registered simulator cells (same cells and test as v27_numbers.py section F)
  M  simulated MDEs for nulls that had none: the E1-0 rerun against its July cell, and
     Qwen3.6-27B's server error against its timeout on Stripe test mode
  P  two-decimal form of a Holm p printed with three decimals elsewhere (Qwen R3 500 vs timeout)
  D  the launch times of the overlapping cross-provider runs (Appendix D) in UTC
  Q  Qwen3.6-27B transcripts whose turns were served by more than one upstream host
Run:  python3 analysis_v27/v28_numbers.py   (the MDE section needs numpy, as in v27)
"""
import collections
import csv
import datetime
import glob
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from v27_common import (RES, ROOT, load, path, short, dedupe_last, holm, fisher_two_sided, mde_sim,
                        f2, pfmt, pe, word, Macros)

OUT = os.path.join(ROOT, "analysis_v27", "out_v28")
TEX = os.environ.get("V28_NUMBERS_TEX", os.path.join(ROOT, "paper-v28", "numbers_v28.tex"))
os.makedirs(OUT, exist_ok=True)


class M28(Macros):
    def put(self, k, v):
        self.d["v28:" + k] = str(v)

    def write(self, fn, extra=""):
        with open(fn, "w") as fh:
            fh.write("% GENERATED by analysis_v27/v28_numbers.py -- do not edit by hand.\n")
            fh.write("% Reads results/ only. Keys are prefixed v28: and never redefine other keys.\n")
            for k, v in self.d.items():
                fh.write("\\defnum{%s}{%s}\n" % (k, v))
            fh.write(extra)


M = M28()
DISP = {"Haiku": "Haiku~4.5", "Sonnet": "Sonnet~5", "Qwen": "Qwen3.6-27B"}


def write_csv(name, rows):
    if not rows:
        return
    with open(os.path.join(OUT, name), "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)


IVR = lambda r: 1.0 if r["violations"] > 0 else 0.0
NJ = json.load(open(path("analysis_v3", "numbers.json")))["numbers"]

# ------------------------------------------------------------------ F: Holm over the Stripe Fisher tests
real = json.load(open(path("analysis_v3", "real_stripe.json")))
frows = []
for k, v in real.items():
    if not isinstance(v, dict) or "within_sim_ci" not in v:
        continue
    s = NJ.get(v.get("sim_key"), {})
    if "k" not in s:
        continue
    frows.append(dict(cell=k, real=f"{v['k']}/{v['n']}", sim=f"{s['k']}/{s['n']}",
                      p_fisher=fisher_two_sided(v["k"], v["n"], s["k"], s["n"])))
adj = holm([r["p_fisher"] for r in frows])
LAB = {"base.none.toA": "timeout", "base.none.e500": "server error", "base.none.w3": "outcome unknown",
       "base.keys.e500": "keys", "restart.amnesiac": "amnesiac", "restart.bare_hint": "bare hint"}
names = []
for r, a in zip(frows, adj):
    r["p_holm"] = a
    if a < 0.05:
        parts = r["cell"].split(":")[0].split(".")
        names.append(f"{DISP[short(parts[1])]} {LAB['.'.join(parts[2:])]}")
nraw = sum(1 for r in frows if r["p_fisher"] < 0.05)
nholm = len(names)
assert len(frows) == 17 and nraw == 6, (len(frows), nraw)   # the v27 numbers (v27:f:n, v27:f:differ)
M.put("f:n", len(frows))
M.put("f:holm:differ", nholm)
M.put("f:holm:differ:w", word(nholm))
M.put("f:holm:cells", "; ".join(names))
write_csv("stripe_fisher_holm.csv", [dict(cell=r["cell"], real=r["real"], sim=r["sim"],
                                          p_fisher=round(r["p_fisher"], 4), p_holm=round(r["p_holm"], 4))
                                     for r in frows])

# ------------------------------------------------------------------ M: MDEs for nulls without one
mrows = []


def MDE(key, label, p0, T_, S=2):
    """Same rule as v27's main-grid MDEs: at the baseline rate, toward the side with more room."""
    sign = +1 if p0 <= 0.5 else -1
    a = mde_sim(p0, sign, T_, S, rho=0)
    b = mde_sim(p0, sign, T_, S, rho=1)
    mrows.append(dict(key=key, label=label, p0=round(p0, 4), sign=sign, T=T_, S=S, mde_indep=a, mde_identical=b))
    sa = f2(a) if a is not None else "--"
    sb = f2(b) if b is not None else "n/a"
    M.put(f"m:{key}:lo", sa)
    M.put(f"m:{key}:hi", sb)
    M.put(f"m:{key}", sa if b is None else (sa if sa == sb else f"{sa}--{sb}"))


# E1-0: the October rerun of Haiku 4.5's keyed timeout cell against the released July cell
jul = dedupe_last(load(path("sweep_raw_v2.jsonl")))
jcell = [r for r in jul if short(r["model"]) == "Haiku" and r["prompt"] == "base" and r["mitigation"] == "idem_keys"
         and r["failure_mode"] == "timeout_after_commit"]
assert int(sum(IVR(r) for r in jcell)) == 59 and len(jcell) == 64      # jul:haiku:base:keys:toA:kn = 59/64
MDE("e10.rerun", "Haiku E1-0 keyed timeout, October rerun vs July", sum(map(IVR, jcell)) / len(jcell),
    len({r["task_id"] for r in jcell}))

# Stripe test mode: Qwen3.6-27B server error vs timeout (paired over its tasks)
rr = [r for r in load(path("real_stripe", "raw.jsonl")) if short(r["model"]) == "Qwen" and r["prompt"] == "base"
      and r["mitigation"] == "none" and r["failure_mode"] == "timeout_after_commit"]
assert int(sum(IVR(r) for r in rr)) == real["real.qwen.base.none.toA:ivr"]["k"] and len(rr) == 32
MDE("real.qwen.500_vs_to", "Qwen Stripe 500 vs timeout", sum(map(IVR, rr)) / len(rr), len({r["task_id"] for r in rr}))
write_csv("mde_v28.csv", mrows)

# ------------------------------------------------------------------ P: two-decimal Holm p
r3 = json.load(open(path("analysis_v3", "r3_wording.json")))["numbers"]
hp = r3["r3.B.qwen.e500_vs_toA:p"]["holm_p"]
M.put("p:qwen.500_vs_to:holm_pe", pe(hp))   # pfmt: two decimals at p >= 0.1, as in Table 15

# ------------------------------------------------------------------ D: launch times in UTC
log = open(path("crossprovider", "run.log")).read()
starts = re.findall(r"=== start \w+ (\w+) (\d+) (\d+):(\d+):(\d+) (P[DS]T|UTC) (\d{4})", log)
assert len(starts) >= 2
MON = {m: i for i, m in enumerate(["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov",
                                   "Dec"], 1)}
for i, (mon, day, hh, mm, ss, tz, yr) in enumerate(starts[:2]):
    off = datetime.timedelta(hours={"PDT": 7, "PST": 8, "UTC": 0}[tz])
    t = datetime.datetime(int(yr), MON[mon], int(day), int(hh), int(mm), int(ss)) + off
    M.put(f"dup:launch{i + 1}:utc", t.strftime("%H:%M UTC"))
    M.put(f"dup:launch{i + 1}:date", f"{t.day} {t.strftime('%B')} {t.year}")

# ------------------------------------------------------------------ Q: Qwen host switches within an episode
nq = nsw = 0
ex = None
for fn in sorted(glob.glob(os.path.join(RES, "**", "*.json"), recursive=True)):
    if "/smoke" in fn or "transcripts" not in fn or "qwen" not in os.path.basename(fn).lower():
        continue
    try:
        t = json.load(open(fn))
    except (ValueError, UnicodeDecodeError):
        continue
    if not isinstance(t, dict) or not isinstance(t.get("turns"), list):
        continue
    ups = [tu.get("provider_meta", {}).get("upstream_provider") for tu in t["turns"]
           if isinstance(tu, dict) and tu.get("role") == "assistant"]
    ups = [u for u in ups if u]
    if not ups:
        continue
    nq += 1
    if len(set(ups)) > 1:
        nsw += 1
M.put("q:hostswitch:k", nsw)
M.put("q:hostswitch:n", f"{nq:,}")
M.put("q:hostswitch:kn", f"{nsw:,}/{nq:,}")

M.write(TEX)
print("wrote", len(M.d), "macros to", TEX)
for k, v in M.d.items():
    print(k, "=", v)
