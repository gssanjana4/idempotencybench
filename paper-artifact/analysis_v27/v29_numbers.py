"""v29 additions to the v27/v28 re-analysis. Reads results/ only and writes
  paper-v29/numbers_v29.tex   (\\defnum{v29:...}{...} and the row macro \\vtwonineStrictRows;
                               never redefines a numbers.tex, v27: or v28: key)
  analysis_v27/out_v29/*.csv   (computed rows, for audit)
No existing output file is rewritten (v27_numbers.py is re-run with its CSVs and its
numbers_v27.tex redirected to a scratch folder, as regen_v27.py does).

Sections
  S  strict raw-string matcher on every registered single-session run (E1-0..E1-6, R1..R4):
     the cells whose duplicate count changes, and R2's Haiku 4.5 status-vs-500 contrast
     (the abstract's cell) under that matcher
  G  the registered verdicts of all experiments split by kind: paired tests, interval
     checks, and the R1 scorer-agreement check (from v27_numbers.py's verdict table)
  C  the logged R3 spend by provider at three decimals, so that the parts add up
Run:  python3 analysis_v27/v29_numbers.py   (numpy, as for v27_numbers.py)
"""
import collections
import csv
import os
import runpy
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import v27_common  # noqa: E402
from v27_common import (ROOT, load, path, short, dedupe_last, paired_contrast, f2, pfmt, pe, dsg,  # noqa: E402
                        word, Macros)

OUT = os.path.join(ROOT, "analysis_v27", "out_v29")
TEX = os.environ.get("V29_NUMBERS_TEX", os.path.join(ROOT, "paper-v29", "numbers_v29.tex"))
os.makedirs(OUT, exist_ok=True)


class M29(Macros):
    def put(self, k, v):
        self.d["v29:" + k] = str(v)

    def write(self, fn, extra=""):
        with open(fn, "w") as fh:
            fh.write("% GENERATED by analysis_v27/v29_numbers.py -- do not edit by hand.\n")
            fh.write("% Reads results/ only. Keys are prefixed v29: and never redefine other keys.\n")
            for k, v in self.d.items():
                fh.write("\\defnum{%s}{%s}\n" % (k, v))
            fh.write(extra)


M = M29()
EXTRA = []
DISP = {"Haiku": "Haiku~4.5", "Sonnet": "Sonnet~5", "Fable": "Fable~5", "GPT": "GPT-5.5", "Gemini": "Gemini",
        "Qwen": "\\qwen{}"}


def write_csv(name, rows):
    if not rows:
        return
    with open(os.path.join(OUT, name), "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)


def prefer_v2(p):
    q = p.replace("raw.jsonl", "raw_v2.jsonl")
    return q if os.path.exists(q) else p


def rows_of(p):
    """Rows as the paper's cells use them: the re-scored file where one exists, the last row of
    an episode run twice, provider refusals out."""
    return dedupe_last([r for r in load(prefer_v2(p)) if not r.get("refusal")])


IVR = lambda r: 1.0 if r["violations"] > 0 else 0.0
IVRS = lambda r: 1.0 if r["violations_strict"] > 0 else 0.0

# ------------------------------------------------------------------ S: strict matcher, registered runs
RUNS = [("E1-0", path("tier1", "e1_0", "raw.jsonl")), ("E1-1", path("tier1", "e1_1", "raw.jsonl")),
        ("E1-2", path("tier1", "e1_2", "raw.jsonl")), ("E1-3", path("tier1", "e1_3", "raw.jsonl")),
        ("E1-4", path("tier1", "e1_4", "raw.jsonl")), ("E1-5", path("tier1", "e1_5", "raw.jsonl")),
        ("E1-6", path("tier1", "e1_6", "raw.jsonl")), ("R1", path("real_stripe", "raw.jsonl")),
        ("R2", path("r2_wording", "raw.jsonl")), ("R3", path("r3_wording", "raw.jsonl")),
        ("R4", path("r4_precommit", "raw.jsonl"))]
FM = {"error_500_after_commit": "server error", "timeout_after_commit": "timeout", "none": "redelivery",
      "status_unknown_after_commit": "``outcome unknown''"}
PR = {"base": "", "careful": ", check-first"}
MIT = {"none": "", "idem_keys": ", keys"}
srows, tex_rows, changed_models = [], [], set()
n_cells = 0
for run, p in RUNS:
    cells = collections.defaultdict(list)
    for r in rows_of(p):
        if "violations_strict" not in r:      # restart rows: graph scoring, no strict field
            continue
        cells[(short(r["model"]), r["prompt"], r["mitigation"], r["failure_mode"])].append(r)
    for (m, pr, mit, fm), v in cells.items():
        n_cells += 1
        k, ks = int(sum(map(IVR, v))), int(sum(map(IVRS, v)))
        assert ks <= k, (run, m, fm)
        if k == ks:
            continue
        changed_models.add(m)
        cond = FM.get(fm, fm) + PR.get(pr, ", " + pr) + MIT.get(mit, ", " + mit)
        srows.append(dict(run=run, model=m, prompt=pr, mitigation=mit, failure_mode=fm, n=len(v), k=k, k_strict=ks))
        note = ""
        if run == "R1":   # Stripe recorded two committed charges in every episode the strict matcher drops
            drop = [r for r in v if r["violations"] > 0 and r["violations_strict"] == 0]
            assert all(r["ivr_stripe"] and r["n_committed_stripe"] >= 2 for r in drop), "R1 strict-only rows"
            note = "$^{*}$"
        tex_rows.append(f"{run} & {DISP[m]} & {cond}{note} & {k}/{len(v)} & {ks}/{len(v)} \\\\")
order = [r for r, _ in RUNS]
key = lambda r: (order.index(r["run"]), list(DISP).index(r["model"]), r["failure_mode"], r["mitigation"], r["prompt"])
idx = sorted(range(len(srows)), key=lambda i: key(srows[i]))
srows, tex_rows = [srows[i] for i in idx], [tex_rows[i] for i in idx]
write_csv("strict_registered.csv", srows)
EXTRA.append("\\def\\vtwonineStrictRows{%%\n%s}\n" % "\n".join(tex_rows))
M.put("s:cells", n_cells)
M.put("s:changed", len(srows))
M.put("s:changed:w", word(len(srows)))
_ms = [DISP[m].replace("\\qwen{}", "Qwen3.6-27B") for m in sorted(changed_models, key=list(DISP).index)]
M.put("s:models", _ms[0] if len(_ms) == 1 else ", ".join(_ms[:-1]) + " and " + _ms[-1])
M.put("s:nmodels:w", word(len(_ms)))
r1 = [r for r in srows if r["run"] == "R1"]
M.put("s:r1:n", len(r1))
M.put("s:r1:dropped", sum(r["k"] - r["k_strict"] for r in r1))

# R2, Haiku 4.5: the abstract's cell (bare 500) and its status contrast under the strict matcher
r2 = collections.defaultdict(list)
for r in rows_of(path("r2_wording", "raw.jsonl")):
    if r.get("failure_mode") not in (None, "none"):
        r2[(short(r["model"]), r["failure_mode"])].append(r)
e5, st = r2[("Haiku", "error_500_after_commit")], r2[("Haiku", "status_unknown_after_commit")]
assert int(sum(map(IVR, e5))) == 42 and len(e5) == 64          # nj:r2.B.haiku.e500:ivr:kn
norm = paired_contrast(st, e5, IVR)
strict = paired_contrast(st, e5, IVRS)
M.put("s:r2haiku500:kn", f"{strict['k_ref']}/{strict['n_ref']}")
M.put("s:r2haiku500:ivr", f2(strict["k_ref"] / strict["n_ref"]))
M.put("s:r2haikustatus:kn", f"{strict['k_cell']}/{strict['n_cell']}")
M.put("s:r2haiku:d", dsg(strict["d"]))
M.put("s:r2haiku:d:norm", dsg(norm["d"]))
M.put("s:r2haiku:ptask:pe", pe(strict["p_task"]))
M.put("s:r2haiku:ptmpl:pe", pe(strict["p_tmpl"]))
M.put("s:r2haiku:ptmpl:sig", "yes" if strict["p_tmpl"] < 0.05 else "no")
write_csv("strict_r2_haiku.csv", [dict(matcher=n, **{k: (round(v, 4) if isinstance(v, float) else v)
                                                     for k, v in c.items()}) for n, c in (("normalized", norm),
                                                                                         ("strict", strict))])

# ------------------------------------------------------------------ G: verdicts by kind
tmp = tempfile.mkdtemp(prefix="v29.v27out.")
v27_common.OUT = tmp
_write = v27_common.Macros.write
v27_common.Macros.write = lambda self, fn, extra="": _write(self, os.path.join(tmp, "numbers_v27.tex"), extra)
_stdout, sys.stdout = sys.stdout, open(os.devnull, "w")
try:
    runpy.run_path(os.path.join(HERE, "v27_numbers.py"), run_name="__main__")
finally:
    sys.stdout.close()
    sys.stdout = _stdout
    v27_common.Macros.write = _write
ver = list(csv.DictReader(open(os.path.join(tmp, "primary_verdicts.csv"))))
kind = lambda r: "test" if r["deciding_p"] else ("agreement" if r["label"] == "R1-H2" else "interval")
grows = []
for kd in ("test", "interval", "agreement"):
    rs = [r for r in ver if kind(r) == kd]
    sup = sum(r["supported"] == "True" for r in rs)
    M.put(f"g:{kd}:n", len(rs))
    M.put(f"g:{kd}:sup", sup)
    M.put(f"g:{kd}:n:w", word(len(rs)))
    M.put(f"g:{kd}:sup:w", word(sup))
    grows += [dict(kind=kd, **r) for r in rs]
M.put("g:all:n", len(ver))
write_csv("verdicts_by_kind.csv", grows)
# the v27 macros the paper printed must agree
v27 = {l.split("}{")[0][8:]: l.split("}{", 1)[1].rstrip("}\n") for l in open(os.path.join(tmp, "numbers_v27.tex"))
       if l.startswith("\\defnum{")}
assert int(v27["v27:p:allexp:n"]) == len(ver)
assert int(v27["v27:p:allexp:ntest"]) == int(M.d["v29:g:test:n"])
assert int(v27["v27:p:allexp:test_sup"]) == int(M.d["v29:g:test:sup"])
assert int(v27["v27:p:cont:n"]) == int(M.d["v29:g:interval:n"]) and int(v27["v27:p:cont:sup"]) == int(M.d["v29:g:interval:sup"])
# E1-0..E1-6 without the E1-1 tests on pre-existing data: both are paired tests and neither is supported
assert int(v27["v27:p:all:n"]) - int(v27["v27:p:nopre:n"]) == int(v27["v27:p:pre:n"])
assert v27["v27:p:all:sup"] == v27["v27:p:nopre:sup"], "an excluded pre-existing-data test was supported"
pre = [r for r in ver if r["label"].startswith("E1-1 ")]
assert len(pre) >= int(v27["v27:p:pre:n"]) and not any(r["supported"] == "True" for r in pre)
M.put("g:e1:tests:nopre:n", int(v27["v27:p:tests:n"]) - int(v27["v27:p:pre:n"]))
M.put("g:e1:tests:nopre:sup", v27["v27:p:tests:sup"])

# ------------------------------------------------------------------ C: R3 spend, parts that add up
r3a = r3o = 0.0
rr = collections.OrderedDict((r["episode_id"], r) for r in load(path("r3_wording", "raw.jsonl")))
for r in rr.values():
    if r["model"].startswith("openrouter:"):
        r3o += r.get("cost_usd") or 0
    else:
        r3a += r.get("cost_usd") or 0
a3, o3 = round(r3a, 3), round(r3o, 3)
M.put("cost:r3_anthropic", f"\\${a3:.3f}")
M.put("cost:r3_openrouter", f"\\${o3:.3f}")
M.put("cost:r3", f"\\${a3 + o3:.3f}")
assert f"{round(r3a + r3o, 2):.2f}" == f"{a3 + o3:.2f}", "three-decimal parts must round to the printed total"
write_csv("r3_spend.csv", [dict(anthropic=r3a, openrouter=r3o, total=r3a + r3o)])

M.write(TEX, "".join(EXTRA))
print("wrote", len(M.d), "macros to", TEX)
for k, v in M.d.items():
    print(k, "=", v)
print("\\vtwonineStrictRows:")
print("\n".join(tex_rows))
